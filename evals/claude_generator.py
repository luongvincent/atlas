"""Claude-subagent generator for the RAG vs CAG eval (replaces the API call in rag_vs_cag.py's run stage).

Gemini's free tier (20 requests/day) couldn't finish the run, so answers are generated by fresh Claude
subagents that see only one prompt file: the exact production /ask prompt, captured by running the real
`core.ask_chain.answer_question` and stopping just before the model call. Subagents never see the eval
set or references. Prompt files have neutral names (pNN) so the arm isn't visible either.

  prepare  -> WORK/prompts/pNN.txt (+ WORK/maps/pNN.json, WORK/index.json)
  (subagents write WORK/answers/pNN.json, and pNN_retry.json when asked to resample)
  ingest   -> evals/results/runs.jsonl via the production citation check; lists prompts needing a resample

Usage: ./venv/Scripts/python.exe evals/claude_generator.py prepare|ingest WORK_DIR
Then: ./venv/Scripts/python.exe evals/rag_vs_cag.py judge && ... report
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from dotenv import load_dotenv

load_dotenv()

HERE = Path(__file__).resolve().parent
EVAL_SET = HERE / "atlas_eval_set.json"
RUNS = HERE / "results" / "runs.jsonl"
GENERATOR = "claude-subagent (Claude Code, Opus 5.5)"

OUTPUT_SPEC = """

Respond with ONLY a JSON object, no other text, in exactly this shape:
{"answer": "<plain-language answer, under 150 words>",
 "citations": [{"claim": "<short paraphrase of the claim>", "excerpt_label": "<label exactly as shown, e.g. E3>",
                "quote": "<under 200 characters copied word for word from that excerpt>"}]}
Use 0 to 4 citations; an empty list if the call didn't cover the question."""


class _Captured(Exception):
    pass


def prepare(work: Path) -> None:
    import core.ask_chain as ask
    from config.tickers import TICKERS_BY_SYMBOL
    from evals.rag_vs_cag import _transcript_docs

    items = json.loads(EVAL_SET.read_text(encoding="utf-8"))
    real_search, real_label = ask._search, ask._label_docs
    captured = {}

    def capture_label(docs, prefix):
        captured["labelled"] = real_label(docs, prefix)
        return captured["labelled"]

    def capture_invoke(prompt):
        captured["prompt"] = prompt
        raise _Captured

    ask._label_docs, ask._invoke = capture_label, capture_invoke
    jobs = [(it, arm) for it in items for arm in ("rag", "cag")]
    random.Random(17).shuffle(jobs)  # neutral, arm-blind file names
    transcripts, index = {}, {}
    for d in ("prompts", "maps", "answers"):
        (work / d).mkdir(parents=True, exist_ok=True)
    for n, (it, arm) in enumerate(jobs):
        key = (it["ticker"], it["quarter"])
        if arm == "cag":
            transcripts.setdefault(key, _transcript_docs(*key))
            ask._search = lambda query, filter, limit, _d=transcripts[key]: list(_d)
        else:
            ask._search = real_search
        try:
            ask.answer_question(it["ticker"], it["quarter"], TICKERS_BY_SYMBOL[it["ticker"]].company_name, it["question"], [])
        except _Captured:
            pass
        pid = f"p{n:02d}"
        (work / "prompts" / f"{pid}.txt").write_text(captured["prompt"] + OUTPUT_SPEC, encoding="utf-8")
        (work / "maps" / f"{pid}.json").write_text(json.dumps(
            {label: {"id": d.id, "text": d.page_content, "metadata": d.metadata} for label, d in captured["labelled"].items()},
            ensure_ascii=False), encoding="utf-8")
        index[pid] = {"arm": arm, "id": it["id"], "prompt_chars": len(captured["prompt"]),
                      "excerpts": len(captured["labelled"])}
    (work / "index.json").write_text(json.dumps(index, indent=1), encoding="utf-8")
    print(f"wrote {len(index)} prompts to {work / 'prompts'}")


def _parse(path: Path):
    import core.ask_chain as ask

    text = path.read_text(encoding="utf-8").strip()
    if text.startswith("```"):
        text = text.split("\n", 1)[1].rsplit("```", 1)[0]
    return ask._LLMAnswer.model_validate_json(text)


def ingest(work: Path) -> None:
    import core.ask_chain as ask
    from langchain_core.documents import Document

    index = json.loads((work / "index.json").read_text(encoding="utf-8"))
    rows, need_retry, missing = [], [], []
    for pid, meta in sorted(index.items()):
        first = work / "answers" / f"{pid}.json"
        if not first.exists():
            missing.append(pid)
            continue
        labelled = {label: Document(id=v["id"], page_content=v["text"], metadata=v["metadata"])
                    for label, v in json.loads((work / "maps" / f"{pid}.json").read_text(encoding="utf-8")).items()}
        attempts, drafted, verified = [], 0, 0
        answer, citations = None, []
        for path in (first, work / "answers" / f"{pid}_retry.json"):  # production: one resample, then refuse
            if not path.exists():
                break
            draft = _parse(path)
            cites = ask._resolve_citations(draft.citations, labelled)
            attempts.append(path.name)
            drafted += len(draft.citations)
            verified += len(cites)
            if cites or not draft.citations:
                answer, citations = draft.answer, cites
                break
        if answer is None:
            if len(attempts) < 2:
                need_retry.append(pid)
                continue
            answer = ask.UNGROUNDED_FALLBACK
        rows.append({
            "arm": meta["arm"], "id": meta["id"], "answer": answer, "citations": [c.model_dump() for c in citations],
            "drafted_citations": drafted, "verified_citations": verified, "attempts": len(attempts),
            "refused": answer == ask.UNGROUNDED_FALLBACK, "input_tokens": meta["prompt_chars"] // 4,
            "tokens_estimated": True, "output_tokens": None, "seconds": None, "model": GENERATOR, "prompt_id": pid,
        })
    if missing or need_retry:
        print(f"missing answers: {missing}\nneed a resample (all citations failed verification): {need_retry}")
        sys.exit(1)
    RUNS.parent.mkdir(exist_ok=True)
    RUNS.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(f"wrote {len(rows)} rows to {RUNS}")


if __name__ == "__main__":
    stage, work = sys.argv[1], Path(sys.argv[2])
    {"prepare": prepare, "ingest": ingest}[stage](work)
